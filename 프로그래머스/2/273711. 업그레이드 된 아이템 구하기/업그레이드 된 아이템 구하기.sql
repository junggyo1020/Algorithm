WITH Ta AS (
    SELECT
        TREE.ITEM_ID
    FROM
        ITEM_INFO INFO
        INNER JOIN ITEM_TREE TREE
        ON INFO.ITEM_ID = PARENT_ITEM_ID
    WHERE
        RARITY = 'RARE'
)

SELECT
    ITEM_INFO.ITEM_ID,
    ITEM_INFO.ITEM_NAME,
    RARITY
FROM
    ITEM_INFO
    INNER JOIN Ta
    ON ITEM_INFO.ITEM_ID = Ta.ITEM_ID
ORDER BY
    ITEM_INFO.ITEM_ID DESC